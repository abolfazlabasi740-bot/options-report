# نگاشت معکوس — ساخته‌شده برنامه‌ای از همان دیکشنری (یکتا بودن پیشوندها لازم است)
PREFIX_TO_UNDERLYING = {v: k for k, v in UNDERLYING_TO_PREFIX.items()}

# جهان ۲۶سهمی: مجموعه‌ی غیرقابل‌تغییر سهم‌های پایه
UNIVERSE = frozenset(UNDERLYING_TO_PREFIX)

# پیشوندها به ترتیب طول نزولی — تا هیچ پیشوندی دیگری را نپوشاند
_PREFIXES_BY_LEN = sorted(PREFIX_TO_UNDERLYING, key=len, reverse=True)


def resolve_underlying(option_symbol):
    # نماد آپشن ← سهم پایه؛ فقط تطابق دقیق پیشوند، در غیر این صورت None
    s = option_symbol or ""
    for p in _PREFIXES_BY_LEN:
        if s.startswith(p):
            return PREFIX_TO_UNDERLYING[p]
    return None


def resolve_option_prefix(underlying):
    # سهم پایه ← پیشوند نماد آپشن (جستجوی ساده دیکشنری)
    return UNDERLYING_TO_PREFIX.get(underlying)


